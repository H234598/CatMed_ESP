#!/usr/bin/env python3
"""Verify the checked-in IDF 6.1 lwIP patch against its pinned upstream blob."""

import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tempfile

REPO = Path(__file__).resolve().parents[1]
MANIFEST_PATH = REPO / "firmware/compat/idf-6.1-lwip-napt-hooks.json"
MANIFEST = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
PATCH = MANIFEST_PATH.parent / MANIFEST["patch"]
SPEC = importlib.util.spec_from_file_location("iot_bridge_compat", REPO / "tools/prepare_iot_bridge_compat.py")
COMPAT = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(COMPAT)


def check(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(message)


def check_fetch_destinations() -> None:
    with tempfile.TemporaryDirectory(prefix="katmed-fetch-conventions-") as tmp:
        root = Path(tmp)
        for convention in ("parent", "component", "unexpected"):
            pending = root / convention
            pending.mkdir()
            destination = pending / "example__component"
            calls = []

            class Fetcher:
                def __init__(self, component, argument):
                    if convention == "parent":
                        self.component_path = argument / component
                    elif convention == "component":
                        self.component_path = argument
                    else:
                        self.component_path = argument / "unexpected"

                def download(self):
                    calls.append(self.component_path)
                    self.component_path.mkdir()
                    (self.component_path / "downloaded").write_bytes(b"fixture")

            try:
                COMPAT._fetch_component(Fetcher, "example__component", pending, destination)
            except ValueError:
                check(convention == "unexpected", "Valid fetch destination rejected")
                check(not calls and not list(pending.iterdir()), "Unexpected destination wrote data")
            else:
                check(convention != "unexpected", "Unexpected fetch destination accepted")
                check(calls == [destination], "Fetcher did not download exactly once to the intended path")
                check((destination / "downloaded").read_bytes() == b"fixture", "Download did not reach destination")
    print("Fetcher parent/component conventions and unexpected destination: passed")


def main() -> None:
    check_fetch_destinations()
    idf = COMPAT._validate_idf_scope(Path(os.environ["IDF_PATH"]))
    check(
        COMPAT._validate_idf_scope(Path("/opt/esp/idf"), "true") == Path("/opt/esp/idf"),
        "Official disposable runner path was not accepted",
    )
    try:
        COMPAT._validate_idf_scope(Path("/tmp/not-an-idf-runner"), "true")
    except ValueError:
        pass
    else:
        raise RuntimeError("Arbitrary CI paths must not be accepted as runner SDKs")
    check(MANIFEST["schema"] == 1, "Unsupported patch manifest schema")
    check(hashlib.sha256(PATCH.read_bytes()).hexdigest() == MANIFEST["patch_sha256"], "Patch hash mismatch")
    lwip = idf / "components/lwip/lwip"
    idf_commit = subprocess.check_output(["git", "-C", str(idf), "rev-parse", "HEAD"], text=True).strip()
    lwip_commit = subprocess.check_output(["git", "-C", str(lwip), "rev-parse", "HEAD"], text=True).strip()
    check(idf_commit == MANIFEST["idf_commit"], "IDF revision mismatch")
    check(lwip_commit == MANIFEST["lwip_commit"], "lwIP revision mismatch")
    upstream = subprocess.check_output(
        ["git", "-C", str(lwip), "show", f"{lwip_commit}:{MANIFEST['source']}"],
    )
    check(hashlib.sha256(upstream).hexdigest() == MANIFEST["source_sha256_before"], "Upstream lwIP source hash mismatch")

    with tempfile.TemporaryDirectory(prefix="katmed-idf6-lwip-patch-") as tmp:
        scratch = Path(tmp)
        source = scratch / MANIFEST["source"]
        source.parent.mkdir(parents=True)
        source.write_bytes(upstream)
        git_env = {**os.environ, "GIT_CEILING_DIRECTORIES": str(scratch.parent)}
        subprocess.run(["git", "-C", str(scratch), "apply", "--check", str(PATCH)], check=True, env=git_env)
        subprocess.run(["git", "-C", str(scratch), "apply", str(PATCH)], check=True, env=git_env)
        result = hashlib.sha256(source.read_bytes()).hexdigest()
        check(result == MANIFEST["source_sha256_after"], "Patch output hash mismatch")
        subprocess.run(["git", "-C", str(scratch), "apply", "--reverse", "--check", str(PATCH)], check=True, env=git_env)
    COMPAT._prepare_idf6_napt(idf, check_only=False)
    # Force a different automatic abbreviation while checking the exact
    # versioned patch generated by the same Git and real patched SDK tree.
    env = {**os.environ, "GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": "core.abbrev", "GIT_CONFIG_VALUE_0": "12"}
    normal = subprocess.check_output(["git", "-C", str(lwip), "diff", "--binary"], env=env)
    fixed = subprocess.check_output(["git", "-C", str(lwip), "diff", "--binary", "--abbrev=7"], env=env)
    check(normal != fixed, "Test did not change Git's automatic diff format")
    check(hashlib.sha256(fixed).hexdigest() == MANIFEST["patch_sha256"], "Explicit lwIP diff format differs from patch")
    print("IDF 6.1 lwIP compatibility patch: manifest, source, apply and reverse-check passed")


if __name__ == "__main__":
    main()
